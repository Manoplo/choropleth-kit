// Generates src/geo/admin1/<cc>.json (one TopoJSON per country) and src/geo/admin1/manifest.json from
// Natural Earth "Admin 1 – States, Provinces" at 1:10m (public domain).
//
//   node scripts/build-geo/build-admin1.mjs                  # downloads the pinned file (cached)
//   node scripts/build-geo/build-admin1.mjs --source <file>  # uses a local copy (the hash is still checked)
//
// Needs Node >= 22.18 (it imports the pure logic straight from `src/geo/admin1-build.ts`). It is run by hand
// when Natural Earth releases a new version; the output IS COMMITTED, like world-110m.json. `topojson-server`
// is a devDependency: the consumer only receives the result.
//
// What it decides (see `src/geo/admin1-build.ts` and FEAT-025):
//   - the id of a unit is its ISO 3166-2 code, or none (placeholders, ambiguous codes);
//   - 1:10m, quantized to a 1e4 grid PER COUNTRY, with no simplification (`topojson-simplify` made the files
//     bigger and the quantization alone already drops what is below the grid);
//   - polygons that quantization leaves wound the wrong way are dropped (d3 would paint the whole map).
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { topology } from "topojson-server";
import {
  countryNames,
  findInvertedUnits,
  normalizeAdmin1,
  pruneInvertedPolygons,
} from "../../src/geo/admin1-build.ts";

const VERSION = "v5.1.1";
const SOURCE_URL = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${VERSION}/geojson/ne_10m_admin_1_states_provinces.geojson`;
const SHA256 = "22d0e3ad85eb3e27f17cabf8ba2d50e554fbc27a87796ff891d958185da62fb5";
const QUANTIZATION = 1e4;
const OUT = "src/geo/admin1";
const CACHE = join("node_modules", ".cache", "choropleth-kit", `ne-admin1-${VERSION}.geojson`);

const sha256 = (buffer) => createHash("sha256").update(buffer).digest("hex");

const sourceFlag = process.argv.indexOf("--source");
const localSource = sourceFlag === -1 ? undefined : process.argv[sourceFlag + 1];

let raw;
if (localSource !== undefined) {
  raw = readFileSync(localSource);
} else if (existsSync(CACHE)) {
  raw = readFileSync(CACHE);
} else {
  console.log(`Downloading ${SOURCE_URL}`);
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`Download failed: ${response.status} ${response.statusText}`);
  raw = Buffer.from(await response.arrayBuffer());
  mkdirSync(dirname(CACHE), { recursive: true });
  writeFileSync(CACHE, raw);
}
const hash = sha256(raw);
if (hash !== SHA256) {
  throw new Error(
    `Natural Earth ${VERSION}: expected sha256 ${SHA256}, got ${hash}. Not building.`,
  );
}

const source = JSON.parse(raw.toString("utf8"));
const { byCountry, report } = normalizeAdmin1(source.features);
const names = countryNames(source.features);

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const countries = {};
let prunedPolygons = 0;
const droppedUnits = [];
for (const country of [...byCountry.keys()].sort()) {
  const units = byCountry.get(country);
  const topo = topology({ admin1: { type: "FeatureCollection", features: units } }, QUANTIZATION);
  const pruned = pruneInvertedPolygons(topo, "admin1");
  prunedPolygons += pruned.polygons;
  for (const id of pruned.droppedUnits) droppedUnits.push(`${country}:${id ?? "(no id)"}`);

  const inverted = findInvertedUnits(topo, "admin1");
  if (inverted.length > 0) throw new Error(`${country}: inverted units after pruning: ${inverted}`);

  const file = join(OUT, `${country.toLowerCase()}.json`);
  writeFileSync(file, JSON.stringify(topo));
  const withoutId = units.filter((u) => u.id === undefined).length;
  countries[country] = {
    name: names.get(country) ?? country,
    units: units.length,
    withoutId,
    bytes: statSync(file).size,
  };
}

const manifest = {
  source: {
    name: "Natural Earth admin-1 states and provinces, 1:10m (public domain)",
    version: VERSION,
    url: SOURCE_URL,
    sha256: SHA256,
  },
  quantization: QUANTIZATION,
  prunedPolygons,
  droppedUnits,
  noCountry: report.noCountry,
  merged: report.merged,
  ambiguous: report.ambiguous,
  countries,
};
writeFileSync(join(OUT, "manifest.json"), `${JSON.stringify(manifest, null, 1)}\n`);

// The table the README links to: generated, so it cannot drift from the data.
const row = (cc, c) =>
  `| \`${cc}\` | ${c.name} | ${c.units}${c.withoutId > 0 ? ` (${c.withoutId} without id)` : ""} | \`choropleth-kit/geo/admin1/${cc.toLowerCase()}\` |`;
const docs = `<!-- GENERATED by scripts/build-geo/build-admin1.mjs. Do not edit by hand. -->

# Subnational geography (admin-1)

The first level below the country, for ${Object.keys(countries).length} countries, from
[Natural Earth](https://www.naturalearthdata.com/) ${VERSION} (public domain) at 1:10m. Each country is its own
module, loaded on demand; see "Subdivisions of a country" in the [README](../README.md).

- **Ids are ISO 3166-2** (\`US-CA\`, \`ES-M\`). A unit without an id is still drawn, as a non-interactive layer.
- **The level is not the same everywhere.** It is what Natural Earth calls admin-1: provinces in Spain (Madrid is
  \`ES-M\`; the autonomous communities, \`ES-MD\`, are not in this data), states in the US, departments in France,
  Länder in Germany. Check the number of units in the table against what you expect before you rely on a country.
- **Disputed borders** (Western Sahara, Kosovo's municipalities, Crimea…) follow Natural Earth. Check them before you
  show a map in a product.
- Units that share an ISO code with a different name (Bosnia's cantons all carry \`BA-BIH\`) have no id, so a join never
  lands on the wrong one: ${report.ambiguous.length} codes, listed under \`ambiguous\` in
  [\`manifest.json\`](../src/geo/admin1/manifest.json).

| Code | Country | Units | Import |
| ---- | ------- | ----- | ------ |
${Object.entries(countries)
  .map(([cc, c]) => row(cc, c))
  .join("\n")}
`;
writeFileSync("docs/geo-admin1.md", docs);

const totalBytes = Object.values(countries).reduce((sum, c) => sum + c.bytes, 0);
const totalUnits = Object.values(countries).reduce((sum, c) => sum + c.units, 0);
console.log(
  `admin1: ${Object.keys(countries).length} countries, ${totalUnits} units ` +
    `(${report.withoutId} without id), ${(totalBytes / 1e6).toFixed(2)} MB raw`,
);
console.log(
  `merged ${report.merged.length} codes, ${report.ambiguous.length} ambiguous codes, ` +
    `${report.noCountry.length} dropped (no country), ${prunedPolygons} inverted polygons pruned`,
);
