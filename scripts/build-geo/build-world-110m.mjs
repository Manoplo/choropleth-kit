// Generates src/geo/world-110m.json and src/geo/iso-numeric-to-alpha2.ts from `world-atlas`
// (Natural Earth, public domain) and `i18n-iso-countries` (only the code table).
//
//   node scripts/build-geo/build-world-110m.mjs
//
// It is run by hand when updating `world-atlas`; the output IS COMMITTED. Neither of the two
// dependencies ships with the library (they are devDependencies): the consumer only receives the result.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const iso = require("i18n-iso-countries");
const atlas = JSON.parse(readFileSync("node_modules/world-atlas/countries-110m.json", "utf8"));

// world-atlas gives no id to these three regions. Kosovo has the commonly used code "XK" (not official
// ISO, but used by the EU, the World Bank and almost every API). Northern Cyprus and Somaliland have
// none: they are left without an id and the library paints them as a non-interactive layer (no holes in the map).
const MANUAL_IDS = { Kosovo: "XK" };

const countries = atlas.objects.countries;
const unresolved = [];
for (const geometry of countries.geometries) {
  const name = geometry.properties?.name;
  if (geometry.id === undefined) {
    const manual = MANUAL_IDS[name];
    if (manual === undefined) unresolved.push(name);
    else geometry.id = manual;
    continue;
  }
  const alpha2 = iso.numericToAlpha2(geometry.id);
  if (alpha2 === undefined) throw new Error(`No alpha-2 for ${geometry.id} (${name})`);
  geometry.id = alpha2;
}

const ids = countries.geometries.map((g) => g.id).filter((id) => id !== undefined);
if (new Set(ids).size !== ids.length) throw new Error("ids alpha-2 duplicados");

writeFileSync("src/geo/world-110m.json", JSON.stringify(atlas));

// Numeric → alpha-2 table for ALL ISO countries, not just those on the map: it serves to convert the
// ids of any geometry (`world-atlas` directly) or of the data.
const table = Object.entries(iso.getAlpha2Codes())
  .map(([alpha2]) => [iso.alpha2ToNumeric(alpha2), alpha2])
  .filter(([numeric]) => numeric !== undefined)
  .sort(([a], [b]) => a.localeCompare(b));

const rows = table.map(([numeric, alpha2]) => `  "${numeric}": "${alpha2}",`).join("\n");
writeFileSync(
  "src/geo/iso-numeric-to-alpha2.ts",
  `// GENERATED by scripts/build-geo/build-world-110m.mjs. Do not edit by hand.
/**
 * ISO 3166-1 numeric → alpha-2 (\`"724"\` → \`"ES"\`). For anyone using \`world-atlas\` directly
 * (its ids are numeric) who has alpha-2 data: \`getFeatureId={(f) => isoNumericToAlpha2[f.id]}\`.
 */
export const isoNumericToAlpha2: Readonly<Record<string, string>> = {
${rows}
};
`,
);

console.log(
  `world-110m: ${countries.geometries.length} regions, without id: ${unresolved.join(", ")}`,
);
console.log(`ISO table: ${table.length} codes`);
